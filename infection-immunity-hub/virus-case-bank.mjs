const CASES=[];
function add(id,lecture,group,subject,stem,alternatives,pages,keyClue,explanation,extraRefs=[],notes={}){
 const labels=[subject,...alternatives];
 if(labels.length!==5||new Set(labels).size!==5||labels.some(key=>!VIRUSES[key]))throw new Error(`Invalid viral comparison: ${id}`);
 const position=[2,4,1,3,0][CASES.length%5];
 labels.splice(0,1);labels.splice(position,0,subject);
 CASES.push({
  id:`lecture-vcase-${id}`,lecture,topic:VIRAL_CASE_TOPIC,format:'mcq',kind:'case',
  subjectId:subject,rotationGroup:group,stem,choices:labels.map(key=>VIRUSES[key][0]),answer:position,
  keyClue,explanation,choiceNotes:labels.map(key=>notes[key]||VIRUSES[key][1]),
  sourceRefs:[{doc:lecture,pages},...extraRefs],examRefs:[],pages,refs:[],tags:['바이러스 통합',group],
  origins:{kind:'강의 기반 새 증례'}
 });
}

